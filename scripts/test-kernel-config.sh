#!/bin/sh
set -eu
CONFIG=$(mktemp)
ARM_CONFIG=$(mktemp)
trap 'rm -f "$CONFIG" "$ARM_CONFIG"' EXIT HUP INT TERM
for option in \
  CONFIG_MODULES CONFIG_MODULE_SIG CONFIG_MODULE_SIG_ALL CONFIG_MODULE_SIG_FORCE \
  CONFIG_MODULE_SIG_SHA256 CONFIG_BLK_DEV_INITRD CONFIG_DEVTMPFS CONFIG_DEVTMPFS_MOUNT \
  CONFIG_EXT4_FS CONFIG_VIRTIO CONFIG_VIRTIO_BLK CONFIG_VIRTIO_NET \
  CONFIG_SERIAL_8250 CONFIG_SERIAL_8250_CONSOLE CONFIG_PROC_FS CONFIG_SYSFS \
  CONFIG_TMPFS CONFIG_CGROUPS CONFIG_CGROUP_PIDS CONFIG_CGROUP_FREEZER \
  CONFIG_CGROUP_SCHED CONFIG_CPUSETS CONFIG_MEMCG CONFIG_NAMESPACES \
  CONFIG_UTS_NS CONFIG_IPC_NS CONFIG_USER_NS CONFIG_PID_NS CONFIG_NET_NS \
  CONFIG_EPOLL CONFIG_EVENTFD CONFIG_SIGNALFD CONFIG_TIMERFD CONFIG_POSIX_MQUEUE \
  CONFIG_UNIX CONFIG_UNIX_DIAG CONFIG_FHANDLE CONFIG_INOTIFY_USER CONFIG_INET \
  CONFIG_SECURITY CONFIG_KEYS CONFIG_AUDIT CONFIG_AUDITSYSCALL \
  CONFIG_BPF CONFIG_BPF_SYSCALL CONFIG_SECCOMP CONFIG_SECCOMP_FILTER \
  CONFIG_IWLWIFI CONFIG_IWLMVM CONFIG_R8169 CONFIG_DRM_I915 \
  CONFIG_NVME_CORE CONFIG_BLK_DEV_NVME CONFIG_SATA_AHCI \
  CONFIG_HP_WMI CONFIG_HP_ACCEL CONFIG_RTW88_8821CE CONFIG_RTW88_8822BE
do
  echo "$option=y" >> "$CONFIG"
done
printf '%s\n' 'CONFIG_LOCALVERSION="-mintosh-xnv"' >> "$CONFIG"
sh scripts/verify-kernel-config.sh "$CONFIG" hp-probook-450-g6 x86_64 >/dev/null
sed -i '/^CONFIG_MODULE_SIG_FORCE=y$/d' "$CONFIG"
if sh scripts/verify-kernel-config.sh "$CONFIG" >/dev/null 2>&1; then
  echo "Kernel config verifier accepted a missing required option." >&2
  exit 1
fi
echo "CONFIG_MODULE_SIG_FORCE=y" >> "$CONFIG"
sed -i '/^CONFIG_RTW88_8821CE=y$/d' "$CONFIG"
if sh scripts/verify-kernel-config.sh "$CONFIG" hp-probook-450-g6 x86_64 >/dev/null 2>&1; then
  echo "Kernel config verifier accepted a missing ProBook Wi-Fi driver." >&2
  exit 1
fi
cp "$CONFIG" "$ARM_CONFIG"
printf '%s\n' 'CONFIG_LOCALVERSION="-mintosh-xnv"' >> "$ARM_CONFIG"
sh scripts/verify-kernel-config.sh "$ARM_CONFIG" generic arm64 >/dev/null
echo "Kernel configuration verification tests passed."
